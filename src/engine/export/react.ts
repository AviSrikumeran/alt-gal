/** input and textarea share everything but the field element. */
function field(type: 'input' | 'textarea'): Built {
  const c = D[type] as Content<'input'>;
  const element =
    type === 'input'
      ? `      <input
        id={fieldId}
        type="text"
        placeholder={placeholder}
        value={value}
        onChange={onChange}
        disabled={disabled}
        aria-invalid={state === 'error' || undefined}
        aria-describedby={help ? helpId : undefined}
        data-part="field"
        style={s.field}
      />`
      : `      <textarea
        id={fieldId}
        rows={4}
        placeholder={placeholder}
        value={value}
        onChange={onChange}
        disabled={disabled}
        aria-invalid={state === 'error' || undefined}
        aria-describedby={help ? helpId : undefined}
        data-part="field"
        style={s.field}
      />`;
  const el = type === 'input' ? 'HTMLInputElement' : 'HTMLTextAreaElement';
  return {
    imports: '',
    extraConst: '',
    props: `  label?: string;
  placeholder?: string;
  helper?: string | null;
  error?: string | null;
  value?: string;
  onChange?: ChangeEventHandler<${el}>;
  disabled?: boolean;`,
    signature: `{ variant = 'primary', size = 'md', label = ${lit(c.label)}, placeholder = ${lit(c.placeholder)}, helper = ${lit(c.helper)}, error = ${lit(c.error)}, value, onChange, disabled }: ${pascal(type)}Props`,
    body: `  const s = STYLES[variant][size];
  const id = useId();
  const fieldId = \`\${id}-field\`;
  const helpId = \`\${id}-help\`;
  const state = error ? 'error' : disabled ? 'disabled' : 'default';
  const help = error ?? helper;
  return (
    <div data-alt="${type}" data-variant={variant} data-size={size} data-state={state} data-part="root" style={s.root}>
      <label htmlFor={fieldId} data-part="label" style={s.label}>
        {label}
      </label>
${element}
      {help && (
        <p id={helpId} data-part="helper" role={state === 'error' ? 'alert' : undefined} style={s.helper}>
          {help}
        </p>
      )}
    </div>
  );`,
  };
}

/** One component file. */
export function exportComponent(type: ComponentType, product: string): ExportFile {
  const name = pascal(type);
  const built = BUILDERS[type]();
  const needsUseId = /useId\(\)/.test(built.body);
  const needsChangeHandler = /ChangeEventHandler/.test(built.props);

  const reactNamed = [needsUseId ? 'useId' : null].filter(Boolean).join(', ');
  const reactTypes = ['CSSProperties', needsChangeHandler ? 'ChangeEventHandler' : null].filter(Boolean).join(', ');

  const contents = `${HEADER(name, product)}
${built.imports ? built.imports + '\n' : ''}${reactNamed ? `import { ${reactNamed} } from 'react';\n` : ''}import type { ${reactTypes} } from 'react';
${PRELUDE}
type Part = ${partsUnion(type, D[type])};

const STYLES: Record<Variant, Record<Size, Record<Part, Decl>>> = ${styleTable(type, D[type])};

${built.extraConst}
export interface ${name}Props {
  variant?: Variant;
  size?: Size;
${built.props}
}

export default function ${name}(${built.signature}) {
${built.body}
}
`;
  return { path: `components/${name}.tsx`, contents, language: 'tsx' };
}

/** Every component type present on the canvas or in a page (D-171). */
export function exportComponents(snap: ExportSnapshot): ExportFile[] {
  return typesPresent(snap)
    .sort()
    .map((type) => exportComponent(type, snap.productName));
}
