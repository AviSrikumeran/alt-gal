/**
 * D-171. One `<PascalCase>.tsx` per component type present, with styles precomputed from the
 * style dictionary at export time — the exported code has no dependency on the studio's engine
 * and reads as plain React. Markup is Turn 3's, with `spec.content.x` replaced by props and every
 * `data-*` attribute retained so the exported `library.css` rules still apply.
 */

const syntheticSpec = <K extends ComponentType>(
  type: K,
  variant: ComponentVariant,
  size: ComponentSize,
  content: ComponentContentMap[K],
): ComponentSpec<K> => ({
  id: 'export',
  type,
  variant,
  size,
  content,
  pageId: null,
  sectionId: null,
  createdBy: 'human',
  createdAt: 0,
});

/** All 15 variant × size combinations for one content shape. */
function styleTable(type: ComponentType, content: ComponentContentMap[ComponentType]): string {
  const def = STYLE_DICTIONARY[type] as ComponentStyleDef;
  const table: Record<string, Record<string, Record<string, CSSProperties>>> = {};
  for (const variant of COMPONENT_VARIANTS) {
    table[variant] = {};
    for (const size of COMPONENT_SIZES)
      table[variant]![size] = def.styles(syntheticSpec(type, variant, size, content) as ComponentSpec);
  }
  return JSON.stringify(table, null, 2);
}

/**
 * Derived from what `styles()` actually returns, not from the declared `parts` list: a few
 * dictionary entries spread a shared builder and produce one part more than they declare
 * (`select` inherits `helper` from the input decls). The emitted type has to match the emitted
 * object, or the exported file will not compile.
 */
const partsUnion = (type: ComponentType, content: ComponentContentMap[ComponentType]): string => {
  const def = STYLE_DICTIONARY[type] as ComponentStyleDef;
  return Object.keys(def.styles(syntheticSpec(type, 'primary', 'md', content) as ComponentSpec))
    .map((p) => `'${p}'`)
    .join(' | ');
};

